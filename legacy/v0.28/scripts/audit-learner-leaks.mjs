function getPlaywright() {
  const candidates = [
    path.join(root, 'node_modules', 'playwright', 'package.json'),
    '/Users/kevinhegg/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/package.json'
  ]
  for (const candidate of candidates) {
    if (fs.existsSync(candidate)) return createRequire(candidate)('playwright')
  }
  throw new Error('Playwright is required for rendered learner-copy leak checks.')
}

function startServer() {
  const child = spawn('npm', ['run', 'dev', '--', '--port', String(port), '--strictPort'], {
    cwd: root,
    stdio: ['ignore', 'pipe', 'pipe'],
    env: { ...process.env, BROWSER: 'none' }
  })
  let output = ''
  child.stdout.on('data', (chunk) => { output += chunk.toString() })
  child.stderr.on('data', (chunk) => { output += chunk.toString() })
  return { child, getOutput: () => output }
}

async function stopServer(child) {
  if (!child || child.killed) return
  child.kill('SIGTERM')
  await new Promise((resolve) => setTimeout(resolve, 500))
  if (!child.killed) child.kill('SIGKILL')
}

async function waitForServer(url, timeoutMs = 30000) {
  const start = Date.now()
  while (Date.now() - start < timeoutMs) {
    try {
      const response = await fetch(url)
      if (response.ok) return
    } catch {
      // keep polling
    }
    await new Promise((resolve) => setTimeout(resolve, 350))
  }
  throw new Error(`Timed out waiting for ${url}`)
}

function contextFor(text, index, length) {
  const start = Math.max(0, index - 90)
  const end = Math.min(text.length, index + length + 90)
  return text.slice(start, end).replace(/\s+/g, ' ').trim()
}

function lineContext(line) {
  return line.replace(/\s+/g, ' ').trim()
}

function allowedReason(file, label, line) {
  if (label === 'generated by' && /generated by (?:the|a) model|Generated by scripts/i.test(line)) {
    return 'Curriculum/internal use: model-generated tokens are being taught, not report provenance.'
  }
  if (label === 'batch' && /tensor|tensors|batch x tokens x features|batch note|batch sheet|positions, features, batches/i.test(line)) {
    return 'Curriculum use: batch is a tensor-axis example, not a development batch.'
  }
  if (label === 'batch' && file === 'src/components/VisualAids.tsx' && />batch</i.test(line)) {
    return 'Curriculum use: batch is a short tensor visual label.'
  }
  if (label === 'batch' && file === 'src/data/promptRun.ts' && /batch-tokens-features|batch as an optional outer dimension/i.test(line)) {
    return 'Curriculum use: batch is a tensor-shape option in Prompt Run.'
  }
  if (label === 'implementation pass' && /implementation pass/i.test(line)) return null
  if (label === 'pilot' && /pilot visual|generate-checkpoint-live-pilot|generate-checkpoint-pilot/i.test(line)) {
    return 'Internal/review-only note or script reference, not normal learner UI.'
  }
  if (label === 'manifest' && file === 'src/components/VisualAids.tsx') {
    return 'Implementation loader for the visual manifest; rendered learner copy is checked separately.'
  }
  if (label === 'fallback' && /(Fallback|fallback|onError|getStored|useStoredState|fallback behavior|quiet-frame)/i.test(line)) {
    return 'Implementation fallback path; normal rendered UI must not expose the word.'
  }
  if (label === 'debug' && /(debug=1|debug|DebugReport|debug-inspector)/i.test(line)) {
    return 'Developer-only debug condition or CSS class; normal rendered UI is checked separately.'
  }
  if ((label === 'v0.' || label === 'v0-') && /(APP_VERSION|review-route|style-guide|printNote|v0\.10|v0\.16|v0-28|v0\.27)/i.test(line)) {
    return 'Developer/review/version metadata, not normal learner UI.'
  }
  if ((label === 'v0.' || label === 'v0-') && /model-literate-badge-v0-27-13\.png/i.test(line)) {
    return 'Internal asset filename; rendered learner UI shows the image, not the versioned file path.'
  }
  if (label === 'legacyCheckpoints' || label === 'checkpointBank') {
    return 'Developer query support for legacy checkpoint comparison, not rendered learner copy.'
  }
  if (label === 'checkpoint bank' && /src\/data\/checkpointBankV02715\.ts/.test(file) && /^\/\/ This checkpoint bank/.test(line.trim())) {
    return 'Internal source-file comment, not rendered learner copy.'
  }
  if (label === 'thumbnail' && /thumbnail/i.test(line)) {
    return 'Internal asset/report support; rendered learner copy is checked separately.'
  }
  return null
}

function renderedAllowedReason(label, context) {
  if (label === 'generated by' && /generated by (?:the|a) model/i.test(context)) {
    return 'Curriculum use: generated response tokens are generated by the model.'
  }
  return null
}

function scanStaticSource() {
  const records = []
  for (const file of checkedFiles) {
    const abs = path.join(root, file)
    if (!fs.existsSync(abs)) continue
    const lines = fs.readFileSync(abs, 'utf8').split(/\r?\n/)
    lines.forEach((line, index) => {
      for (const term of forbiddenTerms) {
        if (!term.pattern.test(line)) continue
        const reason = allowedReason(file, term.label, line)
        records.push({
          source: 'static',
          status: reason ? 'allowed' : 'fail',
          file,
          line: index + 1,
          term: term.label,
          context: lineContext(line),
          reason: reason ?? 'Potential learner-facing developer/process language.'
        })
      }
    })
  }
  return records
}

function evaluateFixedReplacements() {
  return fixedReplacements.map((item) => {
    const abs = path.join(root, item.file)
    const text = fs.existsSync(abs) ? fs.readFileSync(abs, 'utf8') : ''
    return {
      ...item,
      beforeFound: text.includes(item.before),
      afterFound: text.includes(item.after),
      status: !text.includes(item.before) && text.includes(item.after) ? 'fixed' : 'needs-review'
    }
  })
}

async function setAppState(page, { tab, lessonId = null }) {
  await page.goto(`${baseUrl}/?qa=learner-leaks`, { waitUntil: 'load' })
  await page.evaluate(({ nextTab, nextLessonId }) => {
    window.localStorage.setItem('promptlife:v1:lastLocation', JSON.stringify(nextTab))
    if (nextLessonId) window.localStorage.setItem('promptlife:v1:lessonId', JSON.stringify(nextLessonId))
  }, { nextTab: tab, nextLessonId: lessonId })
  await page.reload({ waitUntil: 'load' })
  await page.evaluate(() => document.fonts?.ready)
}

async function waitForImages(page) {
  await page.waitForTimeout(750)
}

async function collectRenderedText(page) {
  return page.evaluate(() => {
    const main = document.querySelector('main#main')
    const text = main?.innerText ?? document.body.innerText ?? ''
    const alts = Array.from(document.querySelectorAll('main#main img[alt]'))
      .map((img) => img.getAttribute('alt'))
      .filter(Boolean)
      .join(' ')
    return `${text}\n${alts}`.trim()
  })
}

async function captureTarget(page, target) {
  if (target.screenshot === false || !target.screenshotName) return null
  const output = path.join(screenshotDir, target.screenshotName)
  if (target.screenshotSelector) {
    await page.setViewportSize({ width: 390, height: 1120 })
    const locator = page.locator(target.screenshotSelector)
    const count = await locator.count()
    if (count === 1) {
      await locator.scrollIntoViewIfNeeded()
      await locator.screenshot({ path: output })
      return path.relative(root, output)
    }
  }
  await page.screenshot({ path: output, fullPage: true })
  return path.relative(root, output)
}

async function runRenderedSmokeCheck() {
  fs.mkdirSync(screenshotDir, { recursive: true })
  const { chromium } = getPlaywright()
  const server = startServer()
  let browser
  try {
    await waitForServer(baseUrl)
    browser = await chromium.launch({
      headless: true,
      executablePath: fs.existsSync('/Applications/Google Chrome.app/Contents/MacOS/Google Chrome')
        ? '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'
        : undefined,
      args: ['--no-sandbox']
    })
    const page = await browser.newPage({ viewport: { width: 390, height: 844 } })
    const rows = []
    for (const target of smokeTargets) {
      await page.setViewportSize({ width: 390, height: 844 })
      await setAppState(page, target)
      await waitForImages(page)
      const text = await collectRenderedText(page)
      const matches = []
      for (const term of renderedForbiddenTerms) {
        const match = term.pattern.exec(text)
        if (!match) continue
        const context = contextFor(text, match.index, match[0].length)
        const reason = renderedAllowedReason(term.label, context)
        if (reason) continue
        matches.push({
          term: term.label,
          context
        })
      }
      const screenshot = await captureTarget(page, target)
      rows.push({
        id: target.id,
        label: target.label,
        status: matches.length ? 'fail' : 'pass',
        url: page.url(),
        screenshot,
        matches
      })
    }
    return {
      status: rows.some((row) => row.status === 'fail') ? 'fail' : 'pass',
      rows
    }
  } catch (error) {
    console.error(server.getOutput())
    throw error
  } finally {
    if (browser) await browser.close()
    await stopServer(server.child)
  }
}

function renderMarkdown(payload) {
  const lines = [
    '# Prompt Life Learner Copy Leak Audit v0.28.8',
    '',
    `Generated: ${payload.generatedAt}`,
    `Status: ${payload.status}`,
    '',
    '## Summary',
    '',
    `- Forbidden terms searched: ${payload.forbiddenTerms.length}`,
    `- Static source records: ${payload.summary.staticRecords}`,
    `- Static failures: ${payload.summary.staticFailures}`,
    `- Static allowed records: ${payload.summary.staticAllowed}`,
    `- Fixed replacement checks: ${payload.summary.fixedReplacements}`,
    `- Rendered smoke status: ${payload.rendered.status}`,
    '',
    '## Fixed Replacements',
    '',
    '| ID | Status | Before | After |',
    '| --- | --- | --- | --- |',
    ...payload.fixedReplacements.map((item) => `| ${item.id} | ${item.status} | ${item.before.replaceAll('|', '\\|')} | ${item.after.replaceAll('|', '\\|')} |`),
    '',
    '## Static Source Records',
    '',
    '| Status | File | Line | Term | Reason | Context |',
    '| --- | --- | ---: | --- | --- | --- |',
    ...payload.staticRecords.map((item) => `| ${item.status} | ${item.file} | ${item.line} | ${item.term} | ${item.reason.replaceAll('|', '\\|')} | ${item.context.replaceAll('|', '\\|')} |`),
    '',
    '## Rendered Smoke Check',
    '',
    '| Status | Screen | Screenshot | Matches |',
    '| --- | --- | --- | --- |',
    ...payload.rendered.rows.map((row) => `| ${row.status} | ${row.label} | ${row.screenshot ?? ''} | ${row.matches.map((match) => `${match.term}: ${match.context}`).join('; ').replaceAll('|', '\\|') || 'none'} |`)
  ]
  return `${lines.join('\n')}\n`
}

async function main() {
  fs.mkdirSync(docsDir, { recursive: true })
  const staticRecords = scanStaticSource()
  const fixed = evaluateFixedReplacements()
  const rendered = process.argv.includes('--static-only')
    ? { status: 'skipped', rows: [] }
    : await runRenderedSmokeCheck()

  const staticFailures = staticRecords.filter((record) => record.status === 'fail')
  const unfixed = fixed.filter((item) => item.status !== 'fixed')
  const renderedFailures = rendered.rows.flatMap((row) => row.matches.map((match) => `${row.label}: ${match.term} (${match.context})`))
  const status = staticFailures.length || unfixed.length || renderedFailures.length ? 'fail' : 'pass'
  const payload = {
    version,
    generatedAt: new Date().toISOString(),
    status,
    forbiddenTerms: forbiddenTerms.map((term) => term.label),
    fixedReplacements: fixed,
    summary: {
      staticRecords: staticRecords.length,
      staticFailures: staticFailures.length,
      staticAllowed: staticRecords.filter((record) => record.status === 'allowed').length,
      fixedReplacements: fixed.filter((item) => item.status === 'fixed').length,
      renderedFailures: renderedFailures.length
    },
    staticRecords,
    rendered
  }

  fs.writeFileSync(jsonPath, `${JSON.stringify(payload, null, 2)}\n`)
  fs.writeFileSync(mdPath, renderMarkdown(payload))

  if (status !== 'pass') {
    console.error('Learner leak audit failed.')
    for (const issue of staticFailures) console.error(`- ${issue.file}:${issue.line} ${issue.term}: ${issue.context}`)
    for (const item of unfixed) console.error(`- Replacement not confirmed: ${item.id}`)
    for (const issue of renderedFailures) console.error(`- Rendered leak: ${issue}`)
    process.exit(1)
  }

  console.log(`Learner leak audit passed. Static records: ${payload.summary.staticRecords}; allowed: ${payload.summary.staticAllowed}; rendered screens: ${rendered.rows.length}.`)
}

main().catch((error) => {
  console.error(error)
  process.exit(1)
})
